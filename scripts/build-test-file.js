#!/usr/bin/env node
// Builds the KoboFlow TEST app from the production candidate, for device
// acceptance testing. Production files are only read, never changed.
//
// The test build is hard-wired to the separate "KoboFlowDB-test" database and
// cannot open, upgrade, read, write, list or delete the live "KoboFlowDB".
// It has its own manifest identity, icons, service worker and cache namespace
// ("koboflow-test-"), so it installs and caches separately from production.
//
//   node scripts/build-test-file.js               → writes koboflow-test.html (single file, for local use)
//   node scripts/build-test-file.js --check       → exits 1 if koboflow-test.html is stale
//   node scripts/build-test-file.js --site <dir>  → writes the complete test site (for the test repository)
//
// The site build is reproducible: the same source commit produces the same bytes.
// SOURCE.json records the source commit and SHA-256 checksums of every input and output.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'koboflow.html');
const OUT = path.join(ROOT, 'koboflow-test.html');
const TEST_DB = 'KoboFlowDB-test';
const LIVE_DB = 'KoboFlowDB';
const PROD_PREFIX = 'koboflow-prod-';
const TEST_PREFIX = 'koboflow-test-';
const TEST_THEME = '#7E22CE';

// Production inputs (read only) and where each lands in the test site.
const INPUTS = ['koboflow.html', 'manifest.json', 'sw.js', 'icons/test-icon-192.png', 'icons/test-icon-512.png', 'package.json', 'scripts/build-test-file.js'];

function replaceOnce(s, from, to, what) {
  const n = s.split(from).length - 1;
  if (n !== 1) throw new Error(`build-test-file: expected exactly one ${what}, found ${n}`);
  return s.replace(from, () => to);
}
const sha256 = buf => crypto.createHash('sha256').update(buf).digest('hex');
const read = rel => fs.readFileSync(path.join(ROOT, rel));

function build(src) {
  let s = src;

  // 1. Guard first: before any app script runs, make the live database unreachable.
  //    Security boundary: this protects code running in the test page itself. IndexedDB
  //    is shared by every page on the origin, so other same-origin pages (production
  //    KoboFlow, other apps, other tabs, extensions) can still open the live database.
  //    Only a separate origin for the test build removes that limitation.
  s = replaceOnce(s, '<script>\n/* KoboFlow IDB Shim v4', `<script>
/* KOBOFLOW TEST BUILD — generated by scripts/build-test-file.js. Do not edit by hand.
   Isolation guard, installed before any app script runs. Two layers:
   1. Database calls: IDBFactory.prototype.open / deleteDatabase / databases are
      patched and locked (non-writable, non-configurable). The name is converted to a
      string once and that exact string is passed on, so a name object cannot change
      value between the check and the real call.
   2. No second realm: every other window (frame, popup, worker) would bring its own,
      unpatched IndexedDB. A blank <iframe> needs no network fetch, so the CSP cannot
      stop it, and window.frames[n] reaches it without any hookable property; a frame
      re-navigated to about:blank even gets a fresh realm. So this page may not create
      frames at all: element creation (createElement/createElementNS, customized
      built-ins) and every HTML-parsing entry point refuse frame/object/embed markup,
      node insertion refuses nodes containing them, and window.open, Worker,
      SharedWorker and foreign service-worker scripts are refused. A MutationObserver
      removes any frame that still appears (last resort; it runs after the current
      script, so it is not relied on).
   Boundary: this guards code running in this page. It cannot stop other same-origin
   pages, browser extensions or devtools from opening the live database. */
(function(g){
  var LIVE = ${JSON.stringify(LIVE_DB)};
  g.__kfTestBuild = true;
  var FRAME_TAG = /^(iframe|frame|frameset|object|embed)$/i, FRAME_MARKUP = /<(i?frame|object|embed)/i, FRAME_SEL = 'iframe,frame,frameset,object,embed';
  function refuse(op){ throw new Error('KoboFlow TEST build: refused to ' + op); }
  function lock(o, k, v){ Object.defineProperty(o, k, { value: v, writable: false, configurable: false, enumerable: false }); }
  function guardRealm(w){
    try {
      var F = w && w.IDBFactory, P = F && F.prototype;
      if (!P || Object.prototype.hasOwnProperty.call(P, '__kfGuard')) return;
      var open = P.open, del = P.deleteDatabase, list = P.databases;
      function wrap(fn, op){ return function(name){ var n = String(name); if (n === LIVE || n.indexOf(LIVE + '-pre-v4-') === 0) refuse(op + ' the live database or its safety copy'); var a = Array.prototype.slice.call(arguments); a[0] = n; return fn.apply(this, a); }; }
      lock(P, 'open', wrap(open, 'open'));
      lock(P, 'deleteDatabase', wrap(del, 'delete'));
      if (typeof list === 'function') lock(P, 'databases', function(){ return list.apply(this, arguments).then(function(d){ return d.filter(function(x){ return x.name !== LIVE && x.name.indexOf(LIVE + '-pre-v4-') !== 0; }); }); });
      lock(P, '__kfGuard', true);
    } catch (e) {}
  }
  guardRealm(g);

  /* Layer 2: no frames, popups or workers. */
  function noFrameMarkup(v){ var t = String(v); if (FRAME_MARKUP.test(t)) refuse('create a frame (frames are not allowed in the test build)'); return t; }
  function noFrameNode(n){
    if (!n || typeof n !== 'object' || !n.nodeType) return;
    if (n.nodeType === 1 && FRAME_TAG.test(n.localName || '')) refuse('insert a frame (frames are not allowed in the test build)');
    if ((n.nodeType === 1 || n.nodeType === 11) && typeof n.querySelector === 'function' && n.querySelector(FRAME_SEL)) refuse('insert a frame (frames are not allowed in the test build)');
  }
  function hook(proto, name, check){
    var d = proto && Object.getOwnPropertyDescriptor(proto, name); if (!d || typeof d.value !== 'function') return;
    var orig = d.value; lock(proto, name, function(){ var a = Array.prototype.slice.call(arguments); check(a); return orig.apply(this, a); });
  }
  function hookSetter(proto, name){
    var d = proto && Object.getOwnPropertyDescriptor(proto, name); if (!d || !d.set) return;
    Object.defineProperty(proto, name, { configurable: false, enumerable: d.enumerable, get: d.get, set: function(v){ return d.set.call(this, noFrameMarkup(v)); } });
  }
  var nodeArgs = function(a){ for (var i = 0; i < a.length; i++) noFrameNode(a[i]); };
  var markupArg = function(i){ return function(a){ if (a.length > i) a[i] = noFrameMarkup(a[i]); }; };
  var allMarkup = function(a){ for (var i = 0; i < a.length; i++) a[i] = noFrameMarkup(a[i]); };
  var D = g.Document && g.Document.prototype, E = g.Element && g.Element.prototype, N = g.Node && g.Node.prototype;
  hook(D, 'createElement', function(a){ a[0] = String(a[0]); if (FRAME_TAG.test(a[0])) refuse('create a frame (frames are not allowed in the test build)'); });
  hook(D, 'createElementNS', function(a){ a[1] = String(a[1]); if (FRAME_TAG.test(a[1].split(':').pop())) refuse('create a frame (frames are not allowed in the test build)'); });
  ['appendChild', 'insertBefore', 'replaceChild'].forEach(function(m){ hook(N, m, nodeArgs); });
  ['Element', 'Document', 'DocumentFragment'].forEach(function(c){ var P = g[c] && g[c].prototype; ['append', 'prepend', 'replaceChildren', 'moveBefore'].forEach(function(m){ if (P && Object.prototype.hasOwnProperty.call(P, m)) hook(P, m, nodeArgs); }); });
  ['Element', 'CharacterData', 'DocumentType'].forEach(function(c){ var P = g[c] && g[c].prototype; ['before', 'after', 'replaceWith'].forEach(function(m){ if (P && Object.prototype.hasOwnProperty.call(P, m)) hook(P, m, nodeArgs); }); });
  hook(E, 'insertAdjacentElement', function(a){ noFrameNode(a[1]); });
  (function(){ var d = D && Object.getOwnPropertyDescriptor(D, 'body'); if (d && d.set) Object.defineProperty(D, 'body', { configurable: false, enumerable: d.enumerable, get: d.get, set: function(v){ noFrameNode(v); return d.set.call(this, v); } }); })();
  hook(g.Range && g.Range.prototype, 'insertNode', nodeArgs);
  hook(g.Range && g.Range.prototype, 'surroundContents', nodeArgs);
  hook(E, 'insertAdjacentHTML', markupArg(1));
  hook(E, 'setHTMLUnsafe', markupArg(0));
  hook(E, 'setHTML', markupArg(0));
  hookSetter(E, 'innerHTML'); hookSetter(E, 'outerHTML');
  if (g.ShadowRoot) { hookSetter(g.ShadowRoot.prototype, 'innerHTML'); hook(g.ShadowRoot.prototype, 'setHTMLUnsafe', markupArg(0)); hook(g.ShadowRoot.prototype, 'setHTML', markupArg(0)); }
  hook(D, 'write', allMarkup); hook(D, 'writeln', allMarkup);
  hook(D, 'execCommand', function(a){ if (/^insert/i.test(String(a[0]))) a[2] = noFrameMarkup(a[2]); });
  hook(D, 'open', function(a){ if (a.length > 2) refuse('open a window (popups are not allowed in the test build)'); });
  hook(g.Range && g.Range.prototype, 'createContextualFragment', markupArg(0));
  hook(g.DOMParser && g.DOMParser.prototype, 'parseFromString', markupArg(0));
  if (g.Document && typeof g.Document.parseHTMLUnsafe === 'function') { var parse = g.Document.parseHTMLUnsafe; lock(g.Document, 'parseHTMLUnsafe', function(h){ return parse.call(this, noFrameMarkup(h)); }); }
  if (g.customElements) hook(g.CustomElementRegistry.prototype, 'define', function(a){ var o = a[2]; if (o && o.extends && FRAME_TAG.test(String(o.extends))) refuse('define a frame element (frames are not allowed in the test build)'); });
  lock(g, 'open', function(){ refuse('open a window (popups are not allowed in the test build)'); });
  ['Worker', 'SharedWorker'].forEach(function(c){ if (g[c]) lock(g, c, function(){ refuse('start a worker (workers are not allowed in the test build)'); }); });
  if (g.ServiceWorkerContainer) {
    var allowedSW = new URL('./test-sw.js', g.location.href).href;
    hook(g.ServiceWorkerContainer.prototype, 'register', function(a){ if (new URL(String(a[0]), g.location.href).href !== allowedSW) refuse('register a service worker other than ./test-sw.js'); a[0] = allowedSW; });
  }
  // Last resort only (runs after the current script): remove any frame that still appears.
  try {
    new g.MutationObserver(function(){ var f = g.document.querySelectorAll(FRAME_SEL); for (var i = 0; i < f.length; i++) { f[i].remove(); g.console.error('KoboFlow TEST build: removed a frame element'); } })
      .observe(g.document.documentElement, { childList: true, subtree: true });
  } catch (e) {}
  // Kept from the previous guard: a frame realm reached through contentWindow/contentDocument is patched too.
  ['HTMLIFrameElement', 'HTMLFrameElement', 'HTMLObjectElement'].forEach(function(c){
    var P = g[c] && g[c].prototype; if (!P) return;
    ['contentWindow', 'contentDocument'].forEach(function(prop){
      var d = Object.getOwnPropertyDescriptor(P, prop); if (!d || !d.get) return;
      Object.defineProperty(P, prop, { configurable: false, enumerable: d.enumerable, get: function(){
        var v = d.get.call(this);
        try { guardRealm(prop === 'contentWindow' ? v : (v && v.defaultView)); } catch (e) {}
        return v;
      } });
    });
  });
})(window);
</script>
<script>
/* KoboFlow IDB Shim v4`, 'IDB shim start');

  // 2. Database name is a constant. No query-string or other input can change it.
  s = replaceOnce(s, `  /* ?db=test (letters, digits, dash) opens a separate test database so trial data
     never touches the real one. Without it the real 'KoboFlowDB' is used. */
  var DB_NAME = 'KoboFlowDB', TEST_DB = null;
  try {
    var m = /[?&]db=([a-z0-9-]{1,24})(?:&|$)/i.exec(g.location.search || '');
    if (m) { TEST_DB = m[1].toLowerCase(); DB_NAME = 'KoboFlowDB-' + TEST_DB; }
  } catch (ex) {}`, `  var DB_NAME = ${JSON.stringify(TEST_DB)}, TEST_DB = 'test'; // TEST BUILD: fixed, cannot be changed`, 'database-name block');

  s = replaceOnce(s, "var db=new Dexie('KoboFlowDB');", "var db=new Dexie(" + JSON.stringify(TEST_DB) + ");", 'Dexie constructor');

  // 3. Visible on first paint, before any script runs.
  s = replaceOnce(s, '<title>KoboFlow &#8212; Track Every Kobo</title>', '<title>KoboFlow TEST &#8212; test database only</title>', 'title');
  s = replaceOnce(s, '  <div id="db-banner"></div>',
    '  <div id="db-banner" style="display:block;background:#7E22CE;color:#fff;border-bottom:2px solid #A855F7;font-size:13px;padding:8px 10px;">TEST DATABASE &mdash; KoboFlowDB-test &mdash; separate from your real records</div>', 'banner element');
  s = replaceOnce(s, "db.textContent=window.__kfTestDb?'TEST DATABASE \"'+window.__kfTestDb+'\" — separate from your real records':'';",
    "db.textContent='TEST DATABASE — KoboFlowDB-test — separate from your real records';db.style.display='block';", 'banner render');
  s = replaceOnce(s, '<div class="brand-tag">Track Every Kobo</div>', '<div class="brand-tag" style="color:#A855F7;">TEST BUILD</div>', 'brand tag');

  // 4. Files exported from the test build are clearly labelled.
  s = replaceOnce(s, "dlFile('koboflow_'+getToday()+'.csv'", "dlFile('koboflow_TEST_'+getToday()+'.csv'", 'CSV filename');
  s = replaceOnce(s, "dlFile('koboflow_backup_'+getToday()+'.json'", "dlFile('koboflow_TEST_backup_'+getToday()+'.json'", 'JSON filename');
  s = replaceOnce(s, "var data={app:'KoboFlow',version:'4.0',", "var data={app:'KoboFlow',testDatabase:" + JSON.stringify(TEST_DB) + ",version:'4.0',", 'backup header');

  // 5. Separate PWA identity: test manifest, test icons, test service worker.
  //    Distinct file names mean a test page can never register the production worker.
  s = replaceOnce(s, '<meta name="theme-color" content="#0A0A0B"/>', `<meta name="theme-color" content="${TEST_THEME}"/>`, 'theme colour');
  // The test page loads no frames, objects or workers of its own (other than its own
  // service worker), so it forbids them: no route to another document's realm.
  s = replaceOnce(s, '<link rel="manifest" href="./manifest.json"/>',
    `<meta http-equiv="Content-Security-Policy" content="frame-src 'none'; child-src 'none'; object-src 'none'; worker-src 'self'"/>\n<link rel="manifest" href="./test-manifest.json"/>`, 'manifest link');
  s = replaceOnce(s, '<link rel="icon" type="image/png" sizes="192x192" href="./icons/icon-192.png"/>', '<link rel="icon" type="image/png" sizes="192x192" href="./icons/test-icon-192.png"/>', 'icon link');
  s = replaceOnce(s, '<link rel="apple-touch-icon" href="./icons/icon-192.png"/>', '<link rel="apple-touch-icon" href="./icons/test-icon-192.png"/>', 'touch icon link');
  s = replaceOnce(s, "var SW_URL='./sw.js';", "var SW_URL='./test-sw.js';", 'service-worker registration');

  // Sanity: the only remaining mention of the live name is inside the guard,
  // and nothing still points at production PWA files.
  const live = s.match(/['"]KoboFlowDB['"]/g) || [];
  if (live.length !== 1) throw new Error('build-test-file: unexpected reference to the live database name');
  if (/\.\/sw\.js|\.\/manifest\.json|icons\/icon-\d+\.png/.test(s)) throw new Error('build-test-file: test page still references a production PWA file');
  return s;
}

function buildManifest(prodJson) {
  const m = JSON.parse(prodJson);
  m.name = 'KoboFlow TEST — test database only';
  m.short_name = 'KoboFlow TEST';
  m.description = 'TEST build of KoboFlow. Uses the separate KoboFlowDB-test database. Fictional data only.';
  m.theme_color = TEST_THEME;
  m.icons = [
    { src: './icons/test-icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: './icons/test-icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: './icons/test-icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ];
  return JSON.stringify(m, null, 2) + '\n';
}

function buildServiceWorker(prodSw) {
  let s = prodSw;
  s = replaceOnce(s, "/* KoboFlow service worker (production).", "/* KoboFlow TEST service worker — generated by scripts/build-test-file.js. Do not edit by hand.", 'service-worker header');
  s = replaceOnce(s, `var APP_PREFIX = '${PROD_PREFIX}';`, `var APP_PREFIX = '${TEST_PREFIX}';`, 'cache prefix');
  s = replaceOnce(s, "var SHELL = ['./', './index.html', './manifest.json', './icons/icon-192.png', './icons/icon-512.png'];",
    "var SHELL = ['./', './index.html', './test-manifest.json', './icons/test-icon-192.png', './icons/test-icon-512.png'];", 'app shell list');
  s = replaceOnce(s, "'KoboFlow is offline and not cached yet. Open it once while online.'", "'KoboFlow TEST is offline and not cached yet. Open it once while online.'", 'offline message');
  if (s.includes(PROD_PREFIX)) throw new Error('build-test-file: test service worker still mentions the production cache prefix');
  return s;
}

function swVersion(sw) {
  const m = /var VERSION = '([^']+)';/.exec(sw);
  if (!m) throw new Error('build-test-file: VERSION not found in sw.js');
  return m[1];
}

function git(args) {
  try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); }
  catch (e) { return null; }
}

// Returns the complete test site as an ordered list of [relativePath, Buffer].
function buildTestSite() {
  const prodSw = read('sw.js').toString('utf8');
  const version = JSON.parse(read('package.json')).version;
  if (swVersion(prodSw) !== version) throw new Error(`build-test-file: sw.js VERSION ${swVersion(prodSw)} does not match package.json ${version}`);
  const files = [
    ['index.html', Buffer.from(build(read('koboflow.html').toString('utf8')))],
    ['test-manifest.json', Buffer.from(buildManifest(read('manifest.json').toString('utf8')))],
    ['test-sw.js', Buffer.from(buildServiceWorker(prodSw))],
    ['icons/test-icon-192.png', read('icons/test-icon-192.png')],
    ['icons/test-icon-512.png', read('icons/test-icon-512.png')],
  ];
  const dirty = git(['status', '--porcelain', '--', ...INPUTS]);
  const source = {
    app: 'KoboFlow TEST',
    purpose: 'Device acceptance testing with fictional data. Not production.',
    sourceRepository: 'uniqueapps-dev/KoboFlow',
    sourceCommit: git(['rev-parse', 'HEAD']) || 'unknown',
    sourceInputsCommitted: dirty === '',
    version,
    database: TEST_DB,
    cacheNamespace: TEST_PREFIX,
    inputs: Object.fromEntries(INPUTS.map(p => [p, sha256(read(p))])),
    files: Object.fromEntries(files.map(([p, b]) => [p, sha256(b)])),
  };
  files.push(['SOURCE.json', Buffer.from(JSON.stringify(source, null, 2) + '\n')]);
  return files;
}

function writeSite(dir) {
  const target = path.resolve(dir);
  if (target === ROOT || target.startsWith(ROOT + path.sep) && !target.startsWith(path.join(ROOT, 'dist') + path.sep))
    throw new Error('build-test-file: write the test site outside the source tree (or under dist/)');
  if (fs.existsSync(target) && fs.readdirSync(target).length && !fs.existsSync(path.join(target, 'SOURCE.json')))
    throw new Error(`build-test-file: ${target} is not empty and was not created by this script; refusing to overwrite`);
  const files = buildTestSite();
  for (const [rel, buf] of files) {
    const p = path.join(target, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, buf);
  }
  return files;
}

module.exports = { build, buildManifest, buildServiceWorker, buildTestSite, writeSite, TEST_PREFIX, PROD_PREFIX };

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.includes('--site')) {
    const dir = args[args.indexOf('--site') + 1];
    if (!dir) { console.error('usage: node scripts/build-test-file.js --site <dir>'); process.exit(2); }
    const files = writeSite(dir);
    const src = JSON.parse(files.find(f => f[0] === 'SOURCE.json')[1]);
    console.log(`wrote test site to ${dir}: ${files.length} files, source ${src.sourceCommit}${src.sourceInputsCommitted ? '' : ' (WITH UNCOMMITTED CHANGES)'}`);
  } else {
    const out = build(fs.readFileSync(SRC, 'utf8'));
    if (args.includes('--check')) {
      const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
      if (cur !== out) { console.error('koboflow-test.html is missing or stale: run node scripts/build-test-file.js'); process.exit(1); }
      console.log('koboflow-test.html is up to date');
    } else {
      fs.writeFileSync(OUT, out);
      console.log('wrote', path.relative(ROOT, OUT), out.length, 'bytes');
    }
  }
}
